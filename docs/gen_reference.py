"""Generate docs/cli.md and docs/python-api.md from the code, so the reference pages cannot drift.

    python docs/gen_reference.py           # rewrite both pages
    python docs/gen_reference.py --check   # exit 1 if they are out of date (the test suite does this too)
"""
from __future__ import annotations

import inspect
import sys
import textwrap
from pathlib import Path

HERE = Path(__file__).resolve().parent


# ---------------------------------------------------------------- CLI
def cli_page() -> str:
    import typer

    from vidlabel.cli import app

    group = typer.main.get_command(app)
    out = ["# Command line reference", "",
           "<!-- generated by docs/gen_reference.py from the code: do not edit by hand -->", "",
           "Every command takes the dataset folder as its first argument. Commands exit with status 1 on an error "
           "(`validate` and `check-video` also do when they find problems), so they work in scripts and CI.", ""]
    for name, cmd in group.commands.items():
        args = [p for p in cmd.params if p.param_type_name == "argument"]
        opts = [p for p in cmd.params if p.param_type_name == "option" and p.name != "help"]
        usage = " ".join(["vidlabel", name] + [a.name + ("..." if a.nargs == -1 else "") for a in args] + (["[options]"] if opts else []))
        out += [f"## `{name}`", "", (cmd.help or "").strip(), "", "```", usage, "```", ""]
        if args:
            out += ["| argument | |", "|---|---|"]
            out += [f"| `{a.name}` | {'required' if a.required else 'optional'} |" for a in args] + [""]
        if opts:
            out += ["| option | default | what it does |", "|---|---|---|"]
            for o in opts:
                flags = " / ".join(f"`{f}`" for f in [*o.opts, *o.secondary_opts])
                if getattr(o, "is_flag", False) or o.secondary_opts:
                    default = "on" if o.default else "off"
                elif o.default in (None, ()) or o.default == []:
                    default = "none"
                else:
                    default = f"`{o.default}`"
                out.append(f"| {flags} | {default} | {(o.help or '').replace('|', '/')} |")
            out.append("")
    return "\n".join(out).rstrip() + "\n"


# ---------------------------------------------------------------- Python API
def _ann(a) -> str:
    return a if isinstance(a, str) else inspect.formatannotation(a)


def _fmt_param(p: inspect.Parameter) -> str:
    text = p.name
    if p.kind is p.VAR_POSITIONAL:
        text = "*" + text
    elif p.kind is p.VAR_KEYWORD:
        text = "**" + text
    if p.annotation is not p.empty:
        text += f": {_ann(p.annotation)}"
    if p.default is not p.empty:
        text += f" = {p.default!r}" if p.annotation is not p.empty else f"={p.default!r}"
    return text


def _sig(obj, name: str) -> str:
    sig = inspect.signature(obj)
    params = [p for p in sig.parameters.values() if p.name != "self"]
    items, star = [], False
    for p in params:
        if p.kind is p.KEYWORD_ONLY and not star and not any(q.kind is q.VAR_POSITIONAL for q in params):
            items.append("*")
            star = True
        items.append(_fmt_param(p))
    ret = "" if sig.return_annotation is inspect.Signature.empty else f" -> {_ann(sig.return_annotation)}"
    one = f"{name}({', '.join(items)}){ret}"
    if len(one) <= 100:
        return one
    return f"{name}(\n" + "".join(f"    {i},\n" for i in items) + f"){ret}"


def _doc(obj) -> str:
    d = inspect.getdoc(obj)
    return d.strip() if d else ""


def _entry(obj, qualname: str, level: str = "###") -> list[str]:
    lines = [f"{level} `{qualname}`", "", "```python", _sig(obj, qualname.split(".")[-1] if "." in qualname and not inspect.isclass(obj) else qualname), "```", ""]
    d = _doc(obj)
    if d:
        lines += [d, ""]
    return lines


def _members(cls, skip=()):
    for n, m in inspect.getmembers(cls):
        if n.startswith("_") or n in skip:
            continue
        if isinstance(m, property):
            yield n, m.fget, True
        elif inspect.isfunction(m) or inspect.ismethod(m):   # ismethod: classmethods such as Dataset.create
            yield n, m, False


def _class_section(cls, qual: str, skip=()) -> list[str]:
    out = [f"### `{qual}`", ""]
    d = _doc(cls)
    out += ["```python", _sig(cls.__init__, qual), "```", ""]
    if d:
        out += [d, ""]
    for n, m, is_prop in _members(cls, skip):
        if is_prop:
            out += [f"#### `{qual}.{n}` (property)", ""]
            if _doc(m):
                out += [_doc(m), ""]
        else:
            out += [f"#### `{qual}.{n}`", "", "```python", _sig(m, n), "```", ""]
            if _doc(m):
                out += [_doc(m), ""]
    return out


def _model_table(model) -> list[str]:
    out = ["| field | type | default | description |", "|---|---|---|---|"]
    for n, f in model.model_fields.items():
        ann = str(f.annotation).replace("<class '", "").replace("'>", "").replace("typing.", "").replace("vidlabel_spec._models.", "")
        default = "required" if f.is_required() else (repr(f.default) if f.default is not None and f.default_factory is None else
                                                      ("empty" if f.default_factory is not None else "none"))
        out.append(f"| `{n}` | `{ann}` | {default} | {(f.description or '').replace('|', '/')} |")
    return out + [""]


def api_page() -> str:
    import vidlabel
    import vidlabel_spec
    import importlib
    from vidlabel import boxes, frames, masks, preview, probe, samples, validate
    build = importlib.import_module("vidlabel.build")   # `vidlabel.build` the attribute is the function, not the module
    from vidlabel.dataset import Dataset

    out = ["# Python API reference", "",
           "<!-- generated by docs/gen_reference.py from the code: do not edit by hand -->", "",
           "Everything below is importable as shown. `from vidlabel import ...` gives the names listed in "
           f"`vidlabel.__all__`; the rest live in the module named in each heading. Concepts and examples are in the other pages "
           "(start with [concepts](concepts.md) and [getting started](getting-started.md)).", "",
           "## Datasets", ""]
    out += _class_section(Dataset, "Dataset")
    out += ["## Releases (compiled training tables)", ""]
    out += _entry(build.build, "vidlabel.build.build")
    out += _class_section(build.Compiled, "vidlabel.build.Compiled")
    out += ["## Training samples", ""]
    out += _class_section(samples.FrameSamples, "vidlabel.samples.FrameSamples")
    out += ["### PyTorch (`vidlabel.torch_data`, needs `vidlabel[torch]`)", ""]
    out += ["`VideoStream` and `VideoFrames` are documented in [training](training.md); `collate_frames(batch)` batches samples "
            "(stacking images that share a size) and `to_tensors(sample)` converts a NumPy sample to tensors (image as uint8 CHW).", ""]
    out += ["## Frames and previews (need OpenCV: `vidlabel[video]`)", ""]
    for n in ("read_frames", "read_frame", "check_video", "crop_to_view", "seek_mismatches"):
        out += _entry(getattr(frames, n), f"vidlabel.frames.{n}")
    out += _class_section(frames.FrameReader, "vidlabel.frames.FrameReader")
    for n in ("render_preview", "draw_annotations", "parse_color"):
        out += _entry(getattr(preview, n), f"vidlabel.preview.{n}")
    out += _class_section(preview.PreviewStyle, "vidlabel.preview.PreviewStyle")
    out += ["## Probing videos (needs ffprobe)", ""]
    out += _entry(probe.probe_video, "vidlabel.probe.probe_video")
    out += _entry(probe.file_hash, "vidlabel.probe.file_hash")
    out += ["## Masks (`vidlabel.masks`)", ""]
    for n in ("encode", "decode", "decode_crop", "bbox", "info", "place_in_frame", "resize_nearest", "from_coco_rle", "to_coco_rle"):
        out += _entry(getattr(masks, n), f"vidlabel.masks.{n}")
    out += ["## Boxes (`vidlabel.boxes`)", ""]
    for n in ("convert_boxes", "rotate_boxes"):
        out += _entry(getattr(boxes, n), f"vidlabel.boxes.{n}")
    out += ["## Validation", ""]
    out += _entry(validate.validate_dataset, "vidlabel.validate_dataset")
    out += _entry(validate.check_annotation_table, "vidlabel.validate.check_annotation_table")
    out += ["### `vidlabel.Issue` and `vidlabel.ValidationError`", "",
            "`validate()` returns a list of `Issue(level, code, message, count, sample_ids)`; `level` is `\"error\"` or `\"warning\"`. "
            "`ValidationError` is raised by writes and by `build` when there are errors; its `.issues` lists them. "
            "The codes are listed in the [spec](SPEC.md#validation-codes).", ""]
    out += ["## Spec models (`vidlabel_spec`, also importable from `vidlabel`)", "",
            "These pydantic models are the contract; unknown fields are rejected (custom data goes in `extra`).", ""]
    for n in ("VideoMetadata", "VideoSource", "Rational", "Region", "View", "Label", "Vocab", "Manifest", "Release"):
        m = getattr(vidlabel_spec, n)
        out += [f"### `{n}`", ""]
        if m.__doc__:
            out += [inspect.cleandoc(m.__doc__), ""]
        out += _model_table(m)
    return "\n".join(out).rstrip() + "\n"


PAGES = {"cli.md": cli_page, "python-api.md": api_page}


def main(argv) -> int:
    sys.path.insert(0, str(HERE.parent / "packages" / "vidlabel" / "src"))
    sys.path.insert(0, str(HERE.parent / "packages" / "vidlabel-spec" / "src"))
    stale = []
    for name, fn in PAGES.items():
        text = fn()
        path = HERE / name
        if "--check" in argv:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        print(f"out of date: {', '.join(stale)}. Run: python docs/gen_reference.py")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
